def _dump(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def _row_to_node(row) -> MemoryNode:
    sources = row["source_transcript_ids"]
    if isinstance(sources, str):
        sources = json.loads(sources)
    return MemoryNode(
        node_id=row["node_id"],
        user_id=row["user_id"],
        agent_id=row["agent_id"],
        parent_path=row["parent_path"],
        path=row["path"],
        title=row["title"],
        summary=row["summary"],
        content=row["content"],
        layer=row["layer"],
        confidence_score=float(row["confidence_score"]),
        verification_status=row["verification_status"],
        salience_tag=row["salience_tag"],
        source_transcript_ids=tuple(str(item) for item in (sources or ())),
        version=int(row["version"]),
        is_deleted=bool(row["is_deleted"]),
        created_at=float(row["created_at"]),
        updated_at=float(row["updated_at"]),
    )


def _l2_index_text(title: str, summary: str, content: str) -> str:
    parts = [part.strip() for part in (title, summary, content) if part and part.strip()]
    return "\n".join(parts)


class SQLiteVFSStore:
    """Zero-dependency SQLite WAL implementation of the relational VFS + L2-only index."""

    def __init__(self, path: str | Path = ":memory:", *, embedder=None, external_vector_index=None):
        self.path = str(path)
        self.embedder = embedder if hasattr(embedder, "encode") and hasattr(embedder, "model_name") else HashedTfidfEmbedder()
        self.external_vector_index = external_vector_index
        self.conn = sqlite3.connect(self.path, timeout=5, check_same_thread=False)
        self.conn.row_factory = sqlite3.Row
        try:
            self.conn.executescript(
                "PRAGMA busy_timeout=5000; PRAGMA journal_mode=WAL; "
                "PRAGMA synchronous=NORMAL; PRAGMA foreign_keys=ON;" + _SQLITE_SCHEMA
            )
        except BaseException:
            self.conn.close()
            raise

    @contextmanager
    def transaction(self):
        if self.conn.in_transaction:
            self.conn.execute("SAVEPOINT vfs_write")
            try:
                yield
            except BaseException:
                self.conn.execute("ROLLBACK TO vfs_write")
                raise
            finally:
                self.conn.execute("RELEASE vfs_write")
        else:
            with self.conn:
                self.conn.execute("BEGIN IMMEDIATE")
                yield

    @contextmanager
    def read_snapshot(self):
        if self.conn.in_transaction:
            yield
        else:
            with self.conn:
                self.conn.execute("BEGIN")
                yield

    def close(self):
        self.conn.close()

    def _encode_l2(self, text: str) -> tuple[str, int, np.ndarray]:
        vec = normalize_vectors(self.embedder.encode([text]))[0].astype(np.float32, copy=False)
        return self.embedder.model_name, len(vec), vec

    def _encode_query(self, query: str) -> tuple[str, int, np.ndarray]:
        encode = getattr(self.embedder, "encode_queries", self.embedder.encode)
        vec = normalize_vectors(encode([query]))[0].astype(np.float32, copy=False)
        return self.embedder.model_name, len(vec), vec

    def _sync_l2_indexes(self, node: MemoryNode) -> None:
        """Hard invariant: ONLY active L2 nodes exist in vector & FTS indexes."""
        self.conn.execute("DELETE FROM memory_node_vectors WHERE node_id=?", (node.node_id,))
        self.conn.execute("DELETE FROM memory_nodes_fts WHERE node_id=?", (node.node_id,))
        if node.layer != "L2" or node.is_deleted:
            if self.external_vector_index is not None:
                self.external_vector_index.delete(node.node_id)
            return
        body = _l2_index_text(node.title, node.summary, node.content)
        if not body:
            return
        model, dim, vec = self._encode_l2(body)
        self.conn.execute(
            "INSERT INTO memory_node_vectors(node_id, user_id, agent_id, model_name, dim, vec) VALUES(?,?,?,?,?,?)",
            (node.node_id, node.user_id, node.agent_id, model, dim, vec.astype("<f4", copy=False).tobytes()),
        )
        self.conn.execute(
            "INSERT INTO memory_nodes_fts(node_id, user_id, agent_id, fts_tokens) VALUES(?,?,?,?)",
            (node.node_id, node.user_id, node.agent_id, tokenize_for_fts(body)),
        )
        if self.external_vector_index is not None:
            self.external_vector_index.upsert_l2(node.to_dict(), vec.tolist())

    def _record_snapshot(
        self,
        row_or_node: MemoryNode,
        *,
        kind: str,
        dream_batch_id: str | None,
        reason: str,
        now: float,
    ) -> str:
        sid = f"snap_{uuid.uuid4().hex[:14]}"
        self.conn.execute(
            """INSERT INTO memory_node_snapshots(
                snapshot_id, node_id, user_id, agent_id, dream_batch_id, snapshot_kind, prev_version,
                parent_path, path, title, summary, content, layer, confidence_score,
                verification_status, salience_tag, source_transcript_ids, is_deleted, reason, created_at
            ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                sid, row_or_node.node_id, row_or_node.user_id, row_or_node.agent_id, dream_batch_id,
                kind, row_or_node.version, row_or_node.parent_path, row_or_node.path,
                row_or_node.title, row_or_node.summary, row_or_node.content, row_or_node.layer,
                row_or_node.confidence_score, row_or_node.verification_status, row_or_node.salience_tag,
                _dump(list(row_or_node.source_transcript_ids)), int(row_or_node.is_deleted), reason, now,
            ),
        )
        return sid

    def get_node(self, path: str, *, user_id: str, agent_id: str, include_deleted: bool = False) -> MemoryNode | None:
        _, norm_path = normalize_node_path(path)
        sql = "SELECT * FROM memory_nodes WHERE user_id=? AND agent_id=? AND path=?"
        if not include_deleted:
            sql += " AND is_deleted=0"
        row = self.conn.execute(sql, (user_id, agent_id, norm_path)).fetchone()
        return _row_to_node(row) if row is not None else None

    def get_node_by_id(self, node_id: str, *, user_id: str, agent_id: str, include_deleted: bool = False) -> MemoryNode | None:
        sql = "SELECT * FROM memory_nodes WHERE user_id=? AND agent_id=? AND node_id=?"
        if not include_deleted:
            sql += " AND is_deleted=0"
        row = self.conn.execute(sql, (user_id, agent_id, node_id)).fetchone()
        return _row_to_node(row) if row is not None else None

    def list_nodes(
        self,
        *,
        user_id: str,
        agent_id: str,
        parent_path: str | None = None,
        recursive: bool = True,
        layer: str | None = None,
        include_deleted: bool = False,
    ) -> list[MemoryNode]:
        clauses = ["user_id=?", "agent_id=?"]
        args: list = [user_id, agent_id]
        if not include_deleted:
            clauses.append("is_deleted=0")
        if layer is not None:
            clauses.append("layer=?")
            args.append(layer)
        if parent_path is not None:
            norm_dir = normalize_dir_path(parent_path)
            if recursive:
                if norm_dir != "/":
                    clauses.append("path LIKE ?")
                    args.append(norm_dir + "%")
            else:
                clauses.append("parent_path=?")
                args.append(norm_dir)
        rows = self.conn.execute(
            f"SELECT * FROM memory_nodes WHERE {' AND '.join(clauses)} ORDER BY path",
            tuple(args),
        ).fetchall()
        return [_row_to_node(row) for row in rows]

    def upsert_node(
        self,
        *,
        user_id: str,
        agent_id: str,
        path: str,
        title: str,
        content: str,
        summary: str = "",
        layer: str = "L2",
        confidence_score: float = 0.7,
        verification_status: str = "unverified",
        salience_tag: str = "normal",
        source_transcript_ids: list[str] | tuple[str, ...] = (),
        expected_version: int | None = None,
        dream_batch_id: str | None = None,
        reason: str = "write",
        timestamp: float | None = None,
    ) -> MemoryNode:
        parent_path, norm_path = normalize_node_path(path)
        validate_node_fields(
            layer=layer,
            confidence_score=confidence_score,
            verification_status=verification_status,
            salience_tag=salience_tag,
        )
        now = time.time() if timestamp is None else float(timestamp)
        sources = list(dict.fromkeys(str(tid) for tid in source_transcript_ids if str(tid).strip()))
        with self.transaction():
            existing_row = self.conn.execute(
                "SELECT * FROM memory_nodes WHERE user_id=? AND agent_id=? AND path=?",
                (user_id, agent_id, norm_path),
            ).fetchone()
            if existing_row is None:
                if expected_version is not None and expected_version != 0:
                    raise OptimisticLockError(norm_path, expected_version, 0)
                node_id = f"node_{uuid.uuid4().hex[:14]}"
                self.conn.execute(
                    """INSERT INTO memory_nodes(
                        node_id, user_id, agent_id, parent_path, path, title, summary, content,
                        layer, confidence_score, verification_status, salience_tag,
                        source_transcript_ids, version, is_deleted, created_at, updated_at
                    ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,1,0,?,?)""",
                    (
                        node_id, user_id, agent_id, parent_path, norm_path, title, summary, content,
                        layer, float(confidence_score), verification_status, salience_tag,
                        _dump(sources), now, now,
                    ),
                )
                node = self.get_node_by_id(node_id, user_id=user_id, agent_id=agent_id, include_deleted=True)
                self._record_snapshot(node, kind="created", dream_batch_id=dream_batch_id, reason=reason, now=now)
                self._sync_l2_indexes(node)
                return node

            existing = _row_to_node(existing_row)
            if expected_version is not None:
                if existing.is_deleted and expected_version == 0:
                    pass
                elif existing.version != expected_version:
                    raise OptimisticLockError(norm_path, expected_version, existing.version)

            self._record_snapshot(existing, kind="before_update", dream_batch_id=dream_batch_id, reason=reason, now=now)
            merged_sources = list(dict.fromkeys([*existing.source_transcript_ids, *sources])) if sources else list(existing.source_transcript_ids)
            cursor = self.conn.execute(
                """UPDATE memory_nodes SET
                    parent_path=?, title=?, summary=?, content=?, layer=?,
                    confidence_score=?, verification_status=?, salience_tag=?,
                    source_transcript_ids=?, version=version+1, is_deleted=0, updated_at=?
                   WHERE node_id=? AND user_id=? AND agent_id=? AND version=?""",
                (
                    parent_path, title, summary, content, layer,
                    float(confidence_score), verification_status, salience_tag,
                    _dump(merged_sources), now,
                    existing.node_id, user_id, agent_id, existing.version,
                ),
            )
            if cursor.rowcount != 1:
                current = self.get_node(norm_path, user_id=user_id, agent_id=agent_id, include_deleted=True)
                raise OptimisticLockError(norm_path, existing.version, current.version if current else 0)
            node = self.get_node_by_id(existing.node_id, user_id=user_id, agent_id=agent_id, include_deleted=True)
            self._sync_l2_indexes(node)
            return node

    def delete_node(
        self,
        *,
        user_id: str,
        agent_id: str,
        path: str,
        expected_version: int | None = None,
        dream_batch_id: str | None = None,
        reason: str = "delete",
        timestamp: float | None = None,
    ) -> bool:
        _, norm_path = normalize_node_path(path)
        now = time.time() if timestamp is None else float(timestamp)
        with self.transaction():
            existing = self.get_node(norm_path, user_id=user_id, agent_id=agent_id, include_deleted=False)
            if existing is None:
                return False
            if expected_version is not None and existing.version != expected_version:
                raise OptimisticLockError(norm_path, expected_version, existing.version)
            self._record_snapshot(existing, kind="before_delete", dream_batch_id=dream_batch_id, reason=reason, now=now)
            cursor = self.conn.execute(
                "UPDATE memory_nodes SET is_deleted=1, version=version+1, updated_at=? WHERE node_id=? AND version=?",
                (now, existing.node_id, existing.version),
            )
            if cursor.rowcount != 1:
                current = self.get_node(norm_path, user_id=user_id, agent_id=agent_id, include_deleted=True)
                raise OptimisticLockError(norm_path, existing.version, current.version if current else 0)
            updated = self.get_node_by_id(existing.node_id, user_id=user_id, agent_id=agent_id, include_deleted=True)
            self._sync_l2_indexes(updated)
            return True

    def list_snapshots(
        self,
        *,
        user_id: str,
        agent_id: str,
        path: str | None = None,
        dream_batch_id: str | None = None,
        limit: int = 20,
    ) -> list[dict]:
        clauses = ["user_id=?", "agent_id=?"]
        args: list = [user_id, agent_id]
        if path is not None:
            _, norm_path = normalize_node_path(path)
            clauses.append("path=?")
            args.append(norm_path)
        if dream_batch_id is not None:
            clauses.append("dream_batch_id=?")
            args.append(dream_batch_id)
        rows = self.conn.execute(
            f"SELECT * FROM memory_node_snapshots WHERE {' AND '.join(clauses)} ORDER BY created_at DESC, snapshot_id DESC LIMIT ?",
            (*args, int(limit)),
        ).fetchall()
        return [
            {**dict(row), "source_transcript_ids": json.loads(row["source_transcript_ids"]), "is_deleted": bool(row["is_deleted"])}
            for row in rows
        ]

    def _restore_snapshot_row(self, snap, *, now: float) -> MemoryNode:
        is_deleted = 1 if snap["snapshot_kind"] == "created" else int(snap["is_deleted"])
        self.conn.execute(
            """UPDATE memory_nodes SET
                parent_path=?, path=?, title=?, summary=?, content=?, layer=?,
                confidence_score=?, verification_status=?, salience_tag=?,
                source_transcript_ids=?, is_deleted=?, version=version+1, updated_at=?
               WHERE node_id=? AND user_id=? AND agent_id=?""",
            (
                snap["parent_path"], snap["path"], snap["title"], snap["summary"], snap["content"], snap["layer"],
                float(snap["confidence_score"]), snap["verification_status"], snap["salience_tag"],
                snap["source_transcript_ids"], is_deleted, now,
                snap["node_id"], snap["user_id"], snap["agent_id"],
            ),
        )
        restored = self.get_node_by_id(snap["node_id"], user_id=snap["user_id"], agent_id=snap["agent_id"], include_deleted=True)
        self._sync_l2_indexes(restored)
        return restored

    def rollback_node(
        self,
        *,
        user_id: str,
        agent_id: str,
        path: str,
        snapshot_id: str | None = None,
        timestamp: float | None = None,
    ) -> MemoryNode:
        _, norm_path = normalize_node_path(path)
        now = time.time() if timestamp is None else float(timestamp)
        with self.transaction():
            if snapshot_id is not None:
                snap = self.conn.execute(
                    "SELECT * FROM memory_node_snapshots WHERE user_id=? AND agent_id=? AND path=? AND snapshot_id=?",
                    (user_id, agent_id, norm_path, snapshot_id),
                ).fetchone()
            else:
                snap = self.conn.execute(
                    """SELECT * FROM memory_node_snapshots
                       WHERE user_id=? AND agent_id=? AND path=?
                       ORDER BY created_at DESC, snapshot_id DESC LIMIT 1""",
                    (user_id, agent_id, norm_path),
                ).fetchone()
            if snap is None:
                raise ValueError(f"no snapshot found for {norm_path}")
            return self._restore_snapshot_row(snap, now=now)

    def rollback_batch(
        self,
        *,
        user_id: str,
        agent_id: str,
        dream_batch_id: str,
        timestamp: float | None = None,
    ) -> list[MemoryNode]:
        """Atomically revert every node touched by a dreaming/consolidation batch."""
        now = time.time() if timestamp is None else float(timestamp)
        with self.transaction():
            rows = self.conn.execute(
                """SELECT * FROM memory_node_snapshots
                   WHERE user_id=? AND agent_id=? AND dream_batch_id=?
                   ORDER BY created_at ASC, snapshot_id ASC""",
                (user_id, agent_id, dream_batch_id),
            ).fetchall()
            if not rows:
                return []
            # Keep the earliest pre-batch snapshot per node so multi-step edits revert cleanly to pre-batch state.
            earliest_by_node = {}
            for row in rows:
                earliest_by_node.setdefault(row["node_id"], row)
            return [self._restore_snapshot_row(snap, now=now) for snap in earliest_by_node.values()]

    def _l2_vector_hits(
        self,
        query: str,
        *,
        user_id: str,
        agent_id: str,
        path_prefix: str | None,
        verified_only: bool,
        salience_tags: tuple[str, ...] | None,
        top_k: int,
    ) -> list[dict]:
        try:
            model, dim, qvec = self._encode_query(query)
        except (OSError, ValueError, TypeError, KeyError, HTTPException):
            return []
        if self.external_vector_index is not None:
            return self.external_vector_index.search_l2(
                qvec.tolist(),
                user_id=user_id,
                agent_id=agent_id,
                path_prefix=path_prefix,
                verified_only=verified_only,
                salience_tags=salience_tags,
                top_k=top_k,
            )
        clauses = ["n.user_id=?", "n.agent_id=?", "n.layer='L2'", "n.is_deleted=0", "v.model_name=?", "v.dim=?"]
        args: list = [user_id, agent_id, model, dim]
        if path_prefix and path_prefix != "/":
            clauses.append("n.path LIKE ?")
            args.append(path_prefix + "%")
        if verified_only:
            clauses.append("n.verification_status='verified'")
        if salience_tags:
            placeholders = ",".join("?" for _ in salience_tags)
            clauses.append(f"n.salience_tag IN ({placeholders})")
            args.extend(salience_tags)
        rows = self.conn.execute(
            f"SELECT v.node_id, v.vec FROM memory_node_vectors v JOIN memory_nodes n ON n.node_id=v.node_id WHERE {' AND '.join(clauses)}",
            tuple(args),
        ).fetchall()
        if not rows:
            return []
        matrix = np.frombuffer(b"".join(row["vec"] for row in rows), dtype="<f4").reshape(-1, dim)
        scores = matrix @ qvec
        hits = [
            {"node_id": row["node_id"], "vector_score": float(score)}
            for row, score in zip(rows, scores)
            if score > 0
        ]
        hits.sort(key=lambda item: (-item["vector_score"], item["node_id"]))
        return hits[:top_k]

    def _l2_lexical_hits(
        self,
        query: str,
        *,
        user_id: str,
        agent_id: str,
        path_prefix: str | None,
        verified_only: bool,
        salience_tags: tuple[str, ...] | None,
        top_k: int,
    ) -> list[dict]:
        terms = list(dict.fromkeys(word for word in tokenize_for_fts(query).split() if word not in _FTS_STOP))
        if not terms:
            return []
        expression = " OR ".join(f'"{term}"' for term in terms[:128])
        clauses = ["memory_nodes_fts MATCH ?", "n.user_id=?", "n.agent_id=?", "n.layer='L2'", "n.is_deleted=0"]
        args: list = [expression, user_id, agent_id]
        if path_prefix and path_prefix != "/":
            clauses.append("n.path LIKE ?")
            args.append(path_prefix + "%")
        if verified_only:
            clauses.append("n.verification_status='verified'")
        if salience_tags:
            placeholders = ",".join("?" for _ in salience_tags)
            clauses.append(f"n.salience_tag IN ({placeholders})")
            args.extend(salience_tags)
        rows = self.conn.execute(
            f"""SELECT n.node_id, bm25(memory_nodes_fts) AS bm25_score
                FROM memory_nodes_fts JOIN memory_nodes n ON n.node_id=memory_nodes_fts.node_id
                WHERE {' AND '.join(clauses)} ORDER BY bm25_score, n.node_id LIMIT ?""",
            (*args, int(top_k)),
        ).fetchall()
        return [{"node_id": row["node_id"], "bm25_score": float(row["bm25_score"])} for row in rows]

    def search_l2(
        self,
        query: str,
        *,
        user_id: str,
        agent_id: str,
        path_prefix: str | None = None,
        verified_only: bool = False,
        salience_tags: tuple[str, ...] | None = None,
        top_k: int = 10,
    ) -> list[dict]:
        """Hybrid vector + BM25 search strictly restricted to active L2 Markdown notes."""
        if not query.strip() or top_k <= 0:
            return []
        norm_prefix = normalize_dir_path(path_prefix) if path_prefix else None
        fetch_k = max(top_k * 2, 20)
        with self.read_snapshot():
            vec_hits = self._l2_vector_hits(
                query, user_id=user_id, agent_id=agent_id, path_prefix=norm_prefix,
                verified_only=verified_only, salience_tags=salience_tags, top_k=fetch_k,
            )
            lex_hits = self._l2_lexical_hits(
                query, user_id=user_id, agent_id=agent_id, path_prefix=norm_prefix,
                verified_only=verified_only, salience_tags=salience_tags, top_k=fetch_k,
            )
            rrf: dict[str, float] = {}
            vec_scores = {h["node_id"]: h["vector_score"] for h in vec_hits}
            for rank, hit in enumerate(vec_hits, start=1):
                rrf[hit["node_id"]] = rrf.get(hit["node_id"], 0.0) + 0.55 / (60 + rank)
            for rank, hit in enumerate(lex_hits, start=1):
                rrf[hit["node_id"]] = rrf.get(hit["node_id"], 0.0) + 0.45 / (60 + rank)
            if not rrf:
                return []
            ids = list(rrf)
            placeholders = ",".join("?" for _ in ids)
            rows = self.conn.execute(
                f"SELECT * FROM memory_nodes WHERE user_id=? AND agent_id=? AND layer='L2' AND is_deleted=0 AND node_id IN ({placeholders})",
                (user_id, agent_id, *ids),
            ).fetchall()
        results = []
        for row in rows:
            node = _row_to_node(row)
            base = rrf[node.node_id] * 61.0
            salience = _SALIENCE_BONUS.get(node.salience_tag, 0.0)
            verified_bonus = 0.06 if node.verification_status == "verified" else 0.0
            score = base * (0.75 + 0.25 * node.confidence_score) + salience + verified_bonus
            results.append({
                **node.to_dict(),
                "score": round(score, 6),
                "vector_score": round(vec_scores.get(node.node_id, 0.0), 6),
            })
        results.sort(key=lambda item: (-item["score"], item["path"]))
        return results[:top_k]

    def vector_index_count(self, *, user_id: str, agent_id: str) -> int:
        row = self.conn.execute(
            "SELECT count(*) FROM memory_node_vectors WHERE user_id=? AND agent_id=?",
            (user_id, agent_id),
        ).fetchone()
        return int(row[0])

    def health_check(self) -> dict:
        return {
            "ok": self.conn.execute("SELECT 1").fetchone()[0] == 1,
            "backend": "sqlite-vfs",
            "vector": "qdrant-l2" if self.external_vector_index is not None else "sqlite-l2-numpy",
            "lexical": "sqlite-fts5-l2",
            "l2_only_embedding": True,
        }


class _PGRow(dict):
    def __getitem__(self, key):
        return super().__getitem__(key) if isinstance(key, str) else tuple(self.values())[key]


def _pg_row_factory(cursor):
    names = [field.name for field in cursor.description or ()]
    return lambda values: _PGRow(zip(names, values))


class _PGResult:
    def __init__(self, rows, rowcount):
        self.rows = iter(rows)
        self.rowcount = rowcount

    def fetchone(self):
        return next(self.rows, None)

    def fetchall(self):
        return list(self.rows)


class _PGConn:
    def __init__(self, pool):
        self.pool = pool
        self.connection = ContextVar("pg_vfs_connection", default=None)

    @contextmanager
    def checkout(self):
        current = self.connection.get()
        if current is not None:
            yield current
        else:
            with self.pool.connection() as connection:
                token = self.connection.set(connection)
                try:
                    yield connection
                finally:
                    self.connection.reset(token)

    def execute(self, sql: str, args=()):
        statement = sql.replace("%", "%%").replace("?", "%s")
        with self.checkout() as connection, connection.cursor() as cursor:
            cursor.execute(statement, args)
            rows = cursor.fetchall() if cursor.description else []
            return _PGResult(rows, cursor.rowcount)


class PostgresVFSStore(SQLiteVFSStore):
    """PostgreSQL VFS store with ACID optimistic locking, snapshots, and L2-only VectorChord/DiskANN/pgvector + BM25."""

    vchord = False
    vectorscale = False
    pg_search = False
    pg_tokenizer = False
    vchord_bm25 = False

    def __init__(self, dsn: str, *, embedder=None, external_vector_index=None):
        try:
            from psycopg import Error
            from psycopg_pool import ConnectionPool
        except ImportError as exc:
            raise RuntimeError("PostgreSQL VFS store requires pip install 'memengine[postgres]'") from exc
        self.embedder = embedder if hasattr(embedder, "encode") and hasattr(embedder, "model_name") else HashedTfidfEmbedder()
        self.external_vector_index = external_vector_index
        self.pool = ConnectionPool(
            dsn, min_size=1, max_size=8, open=False,
            kwargs={"autocommit": True, "row_factory": _pg_row_factory},
        )
        self.conn = _PGConn(self.pool)
        self.pool.open()
        try:
            self.pool.wait(timeout=8)
            with self.transaction():
                self.pgvector = self._enable_extension("vector", Error)
                self.vchord = self._enable_extension("vchord", Error) if self.pgvector else False
                self.vectorscale = self._enable_extension("vectorscale", Error) if self.pgvector else False
                self.pg_search = self._enable_extension("pg_search", Error)
                self.pg_tokenizer = self._enable_extension("pg_tokenizer", Error)
                self.vchord_bm25 = self._enable_extension("vchord_bm25", Error) if self.pg_tokenizer else False
                self._bootstrap()
        except BaseException:
            self.pool.close()
            raise

    def _enable_extension(self, extension: str, error) -> bool:
        try:
            with self.transaction():
                self.conn.execute(f"CREATE EXTENSION IF NOT EXISTS {extension} CASCADE")
        except error as exc:
            if exc.sqlstate not in {"0A000", "42501", "58P01", "22023", "42704"}:
                raise
        return self.conn.execute("SELECT 1 FROM pg_extension WHERE extname=?", (extension,)).fetchone() is not None

    def _vector_engine(self) -> str:
        if self.external_vector_index is not None:
            return "qdrant-l2"
        if self.pgvector and self.vchord:
            return "vchordrq"
        if self.pgvector and self.vectorscale:
            return "diskann"
        if self.pgvector:
            return "pgvector"
        return "sql-array"

    def _lexical_engine(self) -> str:
        if self.pg_search:
            return "pg_search"
        if self.vchord_bm25:
            return "vchord_bm25"
        return "tsvector"

    def _bootstrap(self) -> None:
        for stmt in _PG_SCHEMA.split(";"):
            if stmt.strip():
                self.conn.execute(stmt.strip())
        lexical = self._lexical_engine()
        if lexical == "pg_search":
            self.conn.execute(
                "CREATE INDEX IF NOT EXISTS idx_mn_fts_bm25 ON memory_nodes_fts "
                "USING bm25 (rowid, fts_tokens) WITH (key_field='rowid')"
            )
        elif lexical == "vchord_bm25":
            self.conn.execute(
                "SELECT create_tokenizer('memengine_vfs_ws', '{\"pre_tokenizer\": \"unicode_segmentation\"}')"
            )
            self.conn.execute(
                "ALTER TABLE memory_nodes_fts ADD COLUMN IF NOT EXISTS bm25_tokens bm25vector "
                "GENERATED ALWAYS AS (tokenize(fts_tokens, 'memengine_vfs_ws')::bm25vector) STORED"
            )
            self.conn.execute(
                "CREATE INDEX IF NOT EXISTS idx_mn_fts_vchord_bm25 ON memory_nodes_fts USING bm25 (bm25_tokens bm25_ops)"
            )
        dim = getattr(self.embedder, "dim", None)
        self.indexed_dimensions = [dim] if isinstance(dim, int) and 0 < dim <= 2000 else []
        if self.external_vector_index is None and self.pgvector and self.indexed_dimensions:
            engine = self._vector_engine()
            for d in self.indexed_dimensions:
                if engine == "vchordrq":
                    raw_lists = os.getenv("MEMENGINE_VCHORD_LISTS", "").strip()
                    if raw_lists and not _SAFE_LISTS.match(raw_lists):
                        raise ValueError("MEMENGINE_VCHORD_LISTS must be comma-separated positive integers")
                    opts = f"residual_quantization = true\n[build.internal]\nlists = [{raw_lists}]"
                    self.conn.execute(
                        f"CREATE INDEX IF NOT EXISTS idx_mnv_vchordrq_{d} ON memory_node_vectors "
                        f"USING vchordrq ((vec::vector({d})) vector_cosine_ops) WITH (options = $${opts}$$) WHERE dim={d}"
                    )
                elif engine == "diskann":
                    self.conn.execute(
                        f"CREATE INDEX IF NOT EXISTS idx_mnv_diskann_{d} ON memory_node_vectors "
                        f"USING diskann ((vec::vector({d})) vector_cosine_ops) WHERE dim={d}"
                    )
                else:
                    self.conn.execute(
                        f"CREATE INDEX IF NOT EXISTS idx_mnv_hnsw_{d} ON memory_node_vectors "
                        f"USING hnsw ((vec::vector({d})) vector_cosine_ops) WHERE dim={d}"
                    )

    @contextmanager
    def transaction(self):
        with self.conn.checkout() as connection, connection.transaction():
            yield

    @contextmanager
    def read_snapshot(self):
        if self.conn.connection.get() is not None:
            yield
        else:
            with self.conn.checkout() as connection, connection.transaction():
                connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY")
                yield

    def close(self):
        self.pool.close()

    def _sync_l2_indexes(self, node: MemoryNode) -> None:
        self.conn.execute("DELETE FROM memory_node_vectors WHERE node_id=?", (node.node_id,))
        self.conn.execute("DELETE FROM memory_nodes_fts WHERE node_id=?", (node.node_id,))
        if node.layer != "L2" or node.is_deleted:
            if self.external_vector_index is not None:
                self.external_vector_index.delete(node.node_id)
            return
        body = _l2_index_text(node.title, node.summary, node.content)
        if not body:
            return
        row = self.conn.execute("SELECT rowid FROM memory_nodes WHERE node_id=?", (node.node_id,)).fetchone()
        if row is None:
            return
        model, dim, vec = self._encode_l2(body)
        self.conn.execute(
            "INSERT INTO memory_node_vectors(node_id, user_id, agent_id, model_name, dim, vec) VALUES(?,?,?,?,?,?)",
            (node.node_id, node.user_id, node.agent_id, model, dim, vec.tolist()),
        )
        self.conn.execute(
            "INSERT INTO memory_nodes_fts(rowid, node_id, user_id, agent_id, fts_tokens) VALUES(?,?,?,?,?)",
            (row["rowid"], node.node_id, node.user_id, node.agent_id, tokenize_for_fts(body)),
        )
        if self.external_vector_index is not None:
            self.external_vector_index.upsert_l2(node.to_dict(), vec.tolist())

    def _l2_vector_hits(
        self,
        query: str,
        *,
        user_id: str,
        agent_id: str,
        path_prefix: str | None,
        verified_only: bool,
        salience_tags: tuple[str, ...] | None,
        top_k: int,
    ) -> list[dict]:
        try:
            model, dim, qvec = self._encode_query(query)
        except (OSError, ValueError, TypeError, KeyError, HTTPException):
            return []
        if self.external_vector_index is not None:
            return self.external_vector_index.search_l2(
                qvec.tolist(), user_id=user_id, agent_id=agent_id,
                path_prefix=path_prefix, verified_only=verified_only, salience_tags=salience_tags, top_k=top_k,
            )
        clauses = ["n.user_id=?", "n.agent_id=?", "n.layer='L2'", "n.is_deleted=0", "v.model_name=?", f"v.dim={int(dim)}"]
        args: list = [user_id, agent_id, model]
        if path_prefix and path_prefix != "/":
            clauses.append("n.path LIKE ?")
            args.append(path_prefix + "%")
        if verified_only:
            clauses.append("n.verification_status='verified'")
        if salience_tags:
            placeholders = ",".join("?" for _ in salience_tags)
            clauses.append(f"n.salience_tag IN ({placeholders})")
            args.extend(salience_tags)
        where = " AND ".join(clauses)
        target = qvec.tolist()
        if self.pgvector and dim <= 16000:
            score = f"1-(v.vec::vector({dim}) <=> ?::real[]::vector({dim}))"
            order = f"v.vec::vector({dim}) <=> ?::real[]::vector({dim})"
            params = (target, *args, target, int(top_k))
        else:
            score = "(SELECT sum(x::double precision*y) FROM unnest(v.vec,?::real[]) AS pair(x,y))"
            order = "vector_score DESC, n.node_id"
            params = (target, *args, int(top_k))
        rows = self.conn.execute(
            f"SELECT n.node_id, {score} AS vector_score FROM memory_node_vectors v "
            f"JOIN memory_nodes n ON n.node_id=v.node_id WHERE {where} ORDER BY {order} LIMIT ?",
            params,
        ).fetchall()
        return [
            {"node_id": row["node_id"], "vector_score": float(row["vector_score"])}
            for row in rows
            if row["vector_score"] is not None and row["vector_score"] > 0
        ]

    def _l2_lexical_hits(
        self,
        query: str,
        *,
        user_id: str,
        agent_id: str,
        path_prefix: str | None,
        verified_only: bool,
        salience_tags: tuple[str, ...] | None,
        top_k: int,
    ) -> list[dict]:
        terms = list(dict.fromkeys(word for word in tokenize_for_fts(query).split() if word not in _FTS_STOP))
        if not terms:
            return []
        clauses = ["n.user_id=?", "n.agent_id=?", "n.layer='L2'", "n.is_deleted=0"]
        args: list = [user_id, agent_id]
        if path_prefix and path_prefix != "/":
            clauses.append("n.path LIKE ?")
            args.append(path_prefix + "%")
        if verified_only:
            clauses.append("n.verification_status='verified'")
        if salience_tags:
            placeholders = ",".join("?" for _ in salience_tags)
            clauses.append(f"n.salience_tag IN ({placeholders})")
            args.extend(salience_tags)
        where = " AND ".join(clauses)
        lexical = self._lexical_engine()
        if lexical == "pg_search":
            expression = " OR ".join(f'"{t.replace(chr(34), "")}"' for t in terms[:128] if t.replace('"', ""))
            rows = self.conn.execute(
                f"SELECT n.node_id, -paradedb.score(x.rowid) AS bm25_score FROM memory_nodes_fts x "
                f"JOIN memory_nodes n ON n.rowid=x.rowid WHERE x.fts_tokens @@@ ? AND {where} "
                f"ORDER BY bm25_score, n.node_id LIMIT ?",
                (expression, *args, int(top_k)),
            ).fetchall()
        elif lexical == "vchord_bm25":
            text = " ".join(terms[:128])
            rows = self.conn.execute(
                f"SELECT n.node_id, (x.bm25_tokens <&> to_bm25query('idx_mn_fts_vchord_bm25', tokenize(?, 'memengine_vfs_ws'))) AS bm25_score "
                f"FROM memory_nodes_fts x JOIN memory_nodes n ON n.rowid=x.rowid WHERE {where} "
                f"ORDER BY bm25_score, n.node_id LIMIT ?",
                (text, *args, int(top_k)),
            ).fetchall()
        else:
            expression = " OR ".join(f'"{t}"' for t in terms[:128])
            rows = self.conn.execute(
                f"""WITH q AS (SELECT websearch_to_tsquery('simple', ?) AS ts)
                    SELECT n.node_id, -ts_rank_cd(x.document, q.ts) AS bm25_score
                    FROM memory_nodes_fts x JOIN memory_nodes n ON n.rowid=x.rowid CROSS JOIN q
                    WHERE x.document @@ q.ts AND {where} ORDER BY bm25_score, n.node_id LIMIT ?""",
                (expression, *args, int(top_k)),
            ).fetchall()
        return [{"node_id": row["node_id"], "bm25_score": float(row["bm25_score"])} for row in rows]

    def health_check(self) -> dict:
        return {
            "ok": self.conn.execute("SELECT 1").fetchone()[0] == 1,
            "backend": "postgresql-vfs",
            "vector": self._vector_engine(),
            "lexical": self._lexical_engine(),
            "indexed_dimensions": list(self.indexed_dimensions),
            "l2_only_embedding": True,
        }


def open_vfs_store(db_url: str | Path | None = None, *, embedder=None, external_vector_index=None):
    target = str(db_url or os.getenv("MEMENGINE_VFS_DB_URL") or ":memory:")
    if target.startswith(("postgresql://", "postgres://")):
        return PostgresVFSStore(target, embedder=embedder, external_vector_index=external_vector_index)
    if target.startswith("sqlite:///"):
        target = target.removeprefix("sqlite:///")
    return SQLiteVFSStore(target, embedder=embedder, external_vector_index=external_vector_index)
